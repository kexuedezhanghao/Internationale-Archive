#!/usr/bin/env python3
"""Build readable indexes and a self-contained offline browser from JSON."""
from __future__ import annotations

import argparse
import csv
import io
import json
from collections import Counter, defaultdict
from pathlib import Path
from catalogue_presentation import build_presentations

ROOT = Path(__file__).resolve().parents[1]


def load(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def md(value):
    return str(value or "—").replace("|", "\\|").replace("\n", " ")


def research_index():
    lines = ["# 研究与校勘导航", "", "当前顺序及未决项见[收集进度与待办](../ROADMAP.md)；[2026年10月30日交接摘要](progress-2026-10-30.md)说明本轮同步范围。", "",
             "以下记录按主题列出。每篇的日期、已核范围和未决项分别保留；旧文中的“下一轮”只代表当时安排。", ""]
    groups = defaultdict(list)
    for p in sorted((ROOT / "docs/research").glob("*.md")):
        if p.name == "README.md":
            continue
        name = p.stem
        group = ("中文" if name.startswith(("zh-", "early-zh-")) else
                 "英语" if name.startswith("en-") else "德语" if name.startswith("de-") else
                 "历史进展与交接" if name.startswith("progress-") else "法语、俄语与传播史")
        title = p.read_text(encoding="utf-8").splitlines()[0].removeprefix("# ")
        groups[group].append((title, p.name))
    for group in ["历史进展与交接", "中文", "英语", "德语", "法语、俄语与传播史"]:
        lines += [f"## {group}", ""]
        lines += [f"- [{title}]({path})" for title, path in groups[group]]
        lines += [""]
    lines += ["## 逐字校勘专题", "", "- [鲍狄埃1887年刊本](../collation/fr-pottier-1887.md)",
              "- [瞿秋白1923年前文与谱词](../collation/zh-qu-1923.md)", "",
              "本页由 `scripts/build_catalogue.py` 生成，历史歌词正文保持独立。", ""]
    return "\n".join(lines)


def build_outputs():
    """Return exact generated bytes, allowing read-only freshness checks."""
    entries = load("data/discoveries/antiwarsongs.json")
    versions = load("data/versions.json")
    snapshot = load("data/discoveries/antiwarsongs.snapshot.json")
    displays = build_presentations(versions)
    outputs = {}
    groups = defaultdict(list)
    for r in entries:
        groups[r["language_label_as_reported"] or "Supporting material / 未标语言"].append(r)
    index = ["# 《国际歌》发现目录", "", "生成来源：`data/discoveries/antiwarsongs.json`。", "",
             f"本次快照：**{len(entries)} 个来源条目**，其中 **{snapshot['entries_with_lyrics']} 项在原站有歌词**。这些数字包含转写、回译、改编和资料，**不是独立译本数量**。", "",
             "原站索引自称170种语言；本次页面的语言筛选标签有138种，两者采用不同口径。尚未完成标准语言代码归一与版本去重。", "",
             "已整理的正文与身份记录：[历史版本](versions.md)。也可以打开 [离线检索页](../catalogue.html)。", ""]
    for language in sorted(groups, key=str.casefold):
        rows = groups[language]
        index.extend([f"## {language}", "", "| 来源条目 | 类型建议 | 原站有歌词 | 核对状态 |", "|---|---|---|---|"])
        for r in rows:
            index.append(f"| [{md(r['title_as_reported'])}]({r['source_url']}) | {md(r['kind_suggestion'])} | {'是' if r['has_lyrics_at_source'] else '否'} | {md(r['review_status'])} |")
        index.append("")
    outputs["catalogue/README.md"] = "\n".join(index).encode("utf-8")
    vi = ["# 已整理的历史版本与关联作品", "", "文本是否已收录、出处是否已核对、权利是否已核对分别记录。`source-reviewed` 不等于已与原刊逐字校勘。", "",
          "本页与离线目录使用同一套展示规则。权利状态仅覆盖记录中的具体文字及所列地域；原件影像、编曲和录音另行判断。", "",
          "| 语言 | 版本 | 年代/底本 | 法文段落对应 | 全文 | 校勘状态 | 权利状态 | 说明与研究 |", "|---|---|---|---|---|---|---|---|"]
    for v in versions:
        title = md(v["title_zh"])
        if v["lyrics_path"]:
            title = f"[{title}](../{v['lyrics_path']})"
        else:
            title = f"[{title}]({v['sources'][0]['url']})"
        d = displays[v["id"]]
        vi.append(f"| {md(v['language']['label_zh'])} | {title} | {md(v['edition_label'])} | {md(d['mapping'])} | {'已收录' if v['lyrics_path'] else '仅索引'} | {md(d['collation'])} | {md(d['rights'])} | [版本详情](#{v['id']}) |")
    vi += ["", "## 版本详情", "", "以下统一外层元数据，历史正文的旧字、标点、段序和疑读标记不作整齐化修改。", ""]
    for v in versions:
        d = displays[v["id"]]
        vi += [f"### {v['id']}", "", f"**{v['title_zh']}**", "",
               "| 项目 | 记录 |", "|---|---|",
               f"| 语言 | {md(v['language']['label_zh'])}（{v['language']['tag']}） |",
               f"| 原作者 | {md(v.get('original_author'))} |",
               f"| 译者或文字作者（照记录） | {md(v.get('translator') or v.get('text_author'))} |",
               f"| 采用刊本／底本 | {md(v['edition_label'])} |",
               f"| 法文段落对应 | {md(d['mapping'])} |",
               f"| 校勘状态 | {md(d['collation'])} |",
               f"| 最近记录日期 | {md(v['review'].get('date'))} |",
               f"| 权利状态 | {md(d['rights'])} |", "",
               "**正文**", "",
               f"[阅读历史正文](../{v['lyrics_path']})" if v['lyrics_path'] else "仅索引；本仓库尚未收入全文。", "",
               "**版本说明与校勘**", "",
               f"核对范围（照记录）：{v['review'].get('scope', '具体底本及待核事项见下列来源和版本说明。')}", ""]
        for note in v.get("notes", []):
            vi += [f"- {note}"]
        vi += [""]
        for report in d["reports"]:
            vi += [f"- [{report['label']}](../{report['path']})"]
        vi += ["", "**原始文献与权利**", ""]
        for i, source in enumerate(v["sources"], 1):
            vi += [f"- [来源{i} · {source.get('role', '来源')}]({source['url']})"]
        vi += ["", f"适用范围（照记录）：{v['rights'].get('scope', '待核')}。", ""]
        for basis in v["rights"].get("basis", []):
            vi += [f"- {basis}"]
        for i, url in enumerate(v["rights"].get("evidence_urls", []), 1):
            vi += [f"- [权利依据{i}]({url})"]
        vi += [""]
    vi += ["机器可读记录：[versions.json](../data/versions.json)。研究总导航：[研究与校勘](../docs/research/README.md)。", ""]
    outputs["catalogue/versions.md"] = "\n".join(vi).encode("utf-8")
    with io.StringIO(newline="") as f:
        fields = ["id", "language_label_as_reported", "html_lang_as_reported", "title_as_reported", "kind_suggestion", "has_lyrics_at_source", "year_mentions_in_heading", "source_submission_date", "review_status", "rights_status", "source_url", "canonical_version_ids"]
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in entries:
            w.writerow({k: "; ".join(map(str,r[k])) if isinstance(r[k], list) else r[k] for k in fields})
        outputs["catalogue/discoveries.csv"] = f.getvalue().encode("utf-8-sig")
    stats = {
        "source_entries": len(entries),
        "entries_with_lyrics_at_source": sum(r["has_lyrics_at_source"] for r in entries),
        "supporting_entries": sum(not r["has_lyrics_at_source"] for r in entries),
        "source_language_labels": snapshot["source_language_labels"],
        "source_claimed_languages": snapshot["source_claimed_languages"],
        "curated_records": len(versions),
        "local_full_texts": sum(bool(v["lyrics_path"]) for v in versions),
        "independent_version_total": None,
        "kind_suggestions": dict(sorted(Counter(r["kind_suggestion"] for r in entries).items())),
    }
    outputs["data/stats.json"] = (json.dumps(stats, ensure_ascii=False, indent=2)+"\n").encode("utf-8")
    # Escape '<' so untrusted source headings cannot close the data script.
    payload = json.dumps({"entries":entries,"versions":versions,"stats":stats,"presentation":displays}, ensure_ascii=False).replace("<", "\\u003c")
    template = (ROOT / "scripts/catalogue.template.html").read_text(encoding="utf-8")
    outputs["catalogue.html"] = template.replace("__CATALOGUE_JSON__", payload).encode("utf-8")
    outputs["docs/research/README.md"] = research_index().encode("utf-8")
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on stale generated files without writing")
    args = parser.parse_args()
    outputs = build_outputs()
    stale = []
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        parser.exit(1, "Stale generated files: " + ", ".join(stale) + "\nRun python scripts/build_catalogue.py\n")
    print(f"{'Checked' if args.check else 'Built'} {len(outputs)} catalogue files.")


if __name__ == "__main__":
    main()
